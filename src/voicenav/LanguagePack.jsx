// Helper: Get string with fallback to English
export function t(lang, key) {
  const strings = UI_STRINGS[lang] || UI_STRINGS.en;
  return strings[key] || UI_STRINGS.en[key] || key;
}

// Helper: Get audio prompt with fallback
export function getAudioPrompt(lang, key) {
  const prompts = AUDIO_PROMPTS[lang] || AUDIO_PROMPTS.en;
  return prompts[key] || AUDIO_PROMPTS.en[key] || '';
}

// Helper: Get language info
export function getLanguageInfo(code) {
  return LANGUAGES[code] || LANGUAGES.en;
}

// Helper: Get all languages
export function getAllLanguages() {
  return Object.values(LANGUAGES);
}

// Helper: Get voice commands for an intent
export function getVoiceCommands(intent, lang) {
  const commands = VOICE_COMMANDS.global[intent];
  if (!commands) return [];
  return commands[lang] || commands.en || [];
}

// Helper: Get all voice commands for a language (flat list for all intents)
export function getAllVoiceCommandsForLang(lang) {
  const result = {};
  Object.entries(VOICE_COMMANDS.global).forEach(([intent, langs]) => {
    result[intent] = langs[lang] || langs.en || [];
  });
  return result;
}

